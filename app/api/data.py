"""Data tab backend: GET /api/data/inventory, POST /api/data/{browse_files,import,open}.

Shows what's in the user's data folder -- inputs the app reads, files it
generates, and which file each dashboard actually uses -- and lets the user ADD
files by picking them with the native OS dialog; the server then COPIES them into
the right ``storage/`` subfolder. (Server-side copy is the right approach here: a
browser upload would choke on the ~0.5 GB master DBs / 183 MB MeSH files.)
"""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import sys
from pathlib import Path

from fastapi import APIRouter, HTTPException

from core import paths

router = APIRouter()
_log = logging.getLogger("alexis.api.data")


def _hsize(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{int(n)} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


