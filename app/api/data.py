def _by_key(key: str) -> dict | None:
    return next((c for c in _categories() if c["key"] == key), None)


def _list_files(d: Path, glob: str) -> list[Path]:
    if not d.is_dir():
        return []
    out = []
    for p in d.glob(glob):
        if p.is_file() and p.suffix != ".pyc" and not p.name.startswith("."):
            out.append(p)
    return out


@router.get("/api/data/inventory")
def inventory() -> dict:
    """Per-category file listing with sizes, roles, and the dashboard-current file."""
    cats = []
    for c in _categories():
        d = c["dir"]
        files = _list_files(d, c["glob"])
        files.sort(key=lambda p: p.stat().st_mtime if p.exists() else 0, reverse=True)
        latest_name = files[0].name if (c.get("mark_latest") and files) else None

        total = 0
        rows = []
        LIMIT = 200
        for i, p in enumerate(files):
            try:
                stt = p.stat()
            except OSError:
                continue
            total += stt.st_size
            if i < LIMIT:
                rows.append({
                    "name": p.name, "size": stt.st_size, "size_h": _hsize(stt.st_size),
                    "mtime": int(stt.st_mtime), "latest": (p.name == latest_name),
                })
        cats.append({
            "key": c["key"], "label": c["label"], "desc": c["desc"],
            "roles": c.get("roles", []), "readonly": bool(c.get("readonly")),
            "dir": str(d), "exists": d.is_dir(),
            "count": len(files), "total_size": total, "total_size_h": _hsize(total),
            "shown": len(rows), "files": rows,
        })
    return {"data_dir": str(paths.data_root()), "categories": cats}


@router.post("/api/data/browse_files")
def browse_files() -> dict:
    """Native multi-file picker via the desktop window. Headless -> unavailable
    (the UI then falls back to typing a path)."""
    try:
        from app.main import get_window
        import webview  # type: ignore
    except Exception:  # noqa: BLE001
        return {"paths": [], "available": False}
    win = get_window()
    if win is None:
        return {"paths": [], "available": False}
    try:
        result = win.create_file_dialog(webview.OPEN_DIALOG, allow_multiple=True)
    except Exception as exc:  # noqa: BLE001
        _log.exception("[err] file dialog failed: %s", exc)
        return {"paths": [], "available": True, "error": str(exc)}
    if not result:
        return {"paths": [], "available": True}   # cancelled
    chosen = list(result) if isinstance(result, (list, tuple)) else [str(result)]
    return {"paths": [str(p) for p in chosen], "available": True}


@router.post("/api/data/import")
def import_files(payload: dict) -> dict:
    """Copy chosen source files into the category's storage folder (server-side).

    Sync def on purpose: FastAPI runs it in a threadpool, so a multi-GB copy
    won't block the event loop / health probe.
    """
    if not isinstance(payload, dict):
        raise HTTPException(status_code=400, detail="payload must be a JSON object")
    key = str(payload.get("category") or "").strip()
    sources = payload.get("sources") or []
    if not isinstance(sources, list) or not sources:
        raise HTTPException(status_code=400, detail="sources (a list of file paths) is required")
    cat = _by_key(key)
    if cat is None:
        raise HTTPException(status_code=400, detail=f"unknown category: {key}")
    if cat.get("readonly"):
        raise HTTPException(status_code=400, detail=f"{cat['label']} is read-only (generated by the app)")

    dest = cat["dir"]
    paths.ensure_dir(dest)
    copied, errors = [], []
    for raw in sources:
        try:
            src = Path(str(raw)).expanduser()
            if not src.is_file():
                errors.append({"path": str(raw), "error": "not a file"})
                continue
            target = dest / src.name
            if src.resolve() == target.resolve():
                copied.append({"name": src.name, "note": "already in place"})
                continue
            shutil.copy2(str(src), str(target))
            copied.append({"name": src.name, "size_h": _hsize(target.stat().st_size)})
        except Exception as exc:  # noqa: BLE001
            _log.exception("[err] import copy failed for %s: %s", raw, exc)
            errors.append({"path": str(raw), "error": type(exc).__name__})
    return {"ok": not errors, "category": key, "dest": str(dest), "copied": copied, "errors": errors}


@router.post("/api/data/open")
def open_folder(payload: dict | None = None) -> dict:
    """Open the data folder (or a category subfolder) in the OS file manager."""
    target = paths.data_root()
    if isinstance(payload, dict) and payload.get("category"):
        cat = _by_key(str(payload["category"]))
        if cat is not None:
            target = cat["dir"]
    paths.ensure_dir(target)
    try:
        if sys.platform == "win32":
            os.startfile(str(target))  # type: ignore[attr-defined]  # noqa: S606
        elif sys.platform == "darwin":
            subprocess.Popen(["open", str(target)])
        else:
            subprocess.Popen(["xdg-open", str(target)])
        return {"ok": True, "path": str(target)}
    except Exception as exc:  # noqa: BLE001
        _log.exception("[err] open folder failed: %s", exc)
        raise HTTPException(status_code=500, detail=f"could not open folder: {type(exc).__name__}")
